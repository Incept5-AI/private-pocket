#!/bin/sh
# Pre-build step: turns ble/.env (gitignored) into Generated/DefaultDevice.swift
# (gitignored), so a fresh install already knows your Pocket and, optionally, your
# server. Without .env the app starts empty: add a Pocket in Settings, and speech
# to text and summaries run on the iPhone. See ble/.env.example.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
env="$here/../../ble/.env"
out="$here/Generated/DefaultDevice.swift"
mkdir -p "$here/Generated"

get() {   # get NAME [DEFAULT]: value from .env, quotes stripped
    v=""
    [ -f "$env" ] && v="$(sed -n "s/^$1=//p" "$env" | tail -1 | sed -e 's/[[:space:]]\{1,\}#.*$//' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^"\(.*\)"$/\1/')"
    [ -n "$v" ] && printf '%s' "$v" || printf '%s' "${2:-}"
}
list() {  # comma list -> Swift array literal
    printf '%s' "$1" | awk -F, '{ for (i = 1; i <= NF; i++) { gsub(/^ +| +$/, "", $i); if ($i != "") printf "%s\"%s\"", (n++ ? ", " : ""), $i } }'
}

advertised="$(get POCKET_ADVERTISED)"
key="$(get SERVER_KEY)"
cat > "$out.tmp" <<EOF
// Generated by gen-defaults.sh from ble/.env. Do not commit.
enum DefaultDevice {
    static let name = "$(get POCKET_NAME "${advertised:+Pocket-$(printf '%s' "$advertised" | tail -c 4)}")"
    static let advertisedName = "$advertised"
    static let sessionKey = "$([ -n "$advertised" ] && get POCKET_SK)"
}

/// A server for speech to text, summaries and speakers. Empty url: everything
/// runs on the iPhone until a server is set in Settings.
enum DefaultServer {
    static let name = "$(get SERVER_NAME "default server")"
    static let url = "$(get SERVER_URL)"
    static let sttModel = "$(get STT_MODEL)"
    static let sttModels: [String] = [$(list "$(get STT_MODELS)")]
    static let llmModel = "$(get LLM_MODEL)"
    static let llmModels: [String] = [$(list "$(get LLM_MODELS)")]
    static let diarizeURLs = "$(get DIARIZE_URLS)"
    /// Put in the Keychain on first launch.
    static let key = "$key"
}
EOF
cmp -s "$out.tmp" "$out" 2>/dev/null && rm "$out.tmp" || mv "$out.tmp" "$out"
